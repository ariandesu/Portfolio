import { chromium } from 'playwright-core';
import fs from 'node:fs';
const out = '/private/var/folders/rp/m4y0wkl110j7qhd5k36m0w3m0000gn/T/opencode/qa3';
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
const project = await context.newPage();
await project.goto('http://localhost:3000/projects/shareflow', { waitUntil: 'networkidle' });
await project.evaluate(() => document.fonts.ready);
await project.evaluate(() => document.querySelectorAll('img').forEach((img) => { img.loading = 'eager'; }));
await project.waitForTimeout(1500);
await project.screenshot({ path: `${out}/project-full.png`, fullPage: true });
await project.locator('article > div').first().screenshot({ path: `${out}/project-header.png` });
await project.locator('article figure').first().screenshot({ path: `${out}/project-cover.png` });
await project.locator('article .shell').nth(2).screenshot({ path: `${out}/project-body.png` });

const mobile = await context.newPage();
await mobile.setViewportSize({ width: 390, height: 844 });
await mobile.goto('http://localhost:3000', { waitUntil: 'networkidle' });
await mobile.evaluate(() => document.fonts.ready);
await mobile.evaluate(() => document.querySelectorAll('img').forEach((img) => { img.loading = 'eager'; }));
await mobile.waitForTimeout(1800);
await mobile.locator('#home').screenshot({ path: `${out}/mobile-hero.png` });
await mobile.locator('#about').scrollIntoViewIfNeeded();
await mobile.waitForTimeout(300);
await mobile.locator('#about').screenshot({ path: `${out}/mobile-about.png` });
await mobile.locator('#skills').scrollIntoViewIfNeeded();
await mobile.waitForTimeout(300);
await mobile.locator('#skills').screenshot({ path: `${out}/mobile-skills.png` });
await mobile.locator('#projects').scrollIntoViewIfNeeded();
await mobile.waitForTimeout(500);
await mobile.locator('#projects').screenshot({ path: `${out}/mobile-projects.png` });
await mobile.locator('#contact').scrollIntoViewIfNeeded();
await mobile.waitForTimeout(400);
await mobile.locator('#contact').screenshot({ path: `${out}/mobile-contact.png` });
await mobile.screenshot({ path: `${out}/mobile-contact-viewport.png` });
await mobile.evaluate(() => window.scrollTo(0, 0));
await mobile.waitForTimeout(200);
await mobile.locator('button[aria-label="Open menu"]').click();
await mobile.waitForTimeout(300);
await mobile.screenshot({ path: `${out}/mobile-menu.png` });

const resume = await context.newPage();
await resume.setViewportSize({ width: 1100, height: 1000 });
await resume.goto('http://localhost:3000/resume', { waitUntil: 'networkidle' });
await resume.evaluate(() => document.fonts.ready);
await resume.waitForTimeout(500);
await resume.screenshot({ path: `${out}/resume-screen.png`, fullPage: true });
await browser.close();
